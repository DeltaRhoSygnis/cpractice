#!/usr/bin/env node
/**
 * Generate .opencode/RULES.md — an index of the vendored rule packs.
 *
 * Rules are reference material, not always-on instructions. OpenCode V2 loads
 * AGENTS.md only (the `instructions` array is not resolved), so rules are kept
 * as a browsable library that an agent reads on demand. AGENTS.md points here.
 *
 * Usage: node .opencode/scripts/generate-rules-index.mjs
 */

import * as fs from "node:fs"
import * as path from "node:path"

const opencodeDir = path.resolve(import.meta.dirname, "..")
const rulesDir = path.join(opencodeDir, "rules")

if (!fs.existsSync(rulesDir)) {
  console.error("No .opencode/rules directory; nothing to index.")
  process.exit(1)
}

function title(file) {
  const text = fs.readFileSync(file, "utf-8")
  const heading = text.match(/^#\s+(.+)$/m)
  return heading ? heading[1].trim() : path.basename(file, ".md")
}

function firstParagraph(file) {
  const text = fs.readFileSync(file, "utf-8")
  const body = text.replace(/^#.*$/m, "").trim()
  const para = body.split(/\n\s*\n/).find((p) => p.trim() && !p.trim().startsWith("```"))
  return para ? para.replace(/\s+/g, " ").trim().slice(0, 180) : ""
}

const packs = fs
  .readdirSync(rulesDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort()

const commonDir = path.join(rulesDir, "common")
const common = fs.existsSync(commonDir)
  ? fs.readdirSync(commonDir).filter((f) => f.endsWith(".md")).sort()
  : []

const lines = []
lines.push("# ECC Rules Index (generated)")
lines.push("")
lines.push("> Generated by `.opencode/scripts/generate-rules-index.mjs`. Do not edit by hand.")
lines.push(">")
lines.push("> These are **reference** rules, not always-on instructions. Read the ones")
lines.push("> relevant to the task. OpenCode V2 loads `AGENTS.md` only, so rules are not")
lines.push("> injected automatically.")
lines.push("")
const packCount = packs.filter((p) => p !== "common").length
lines.push(`Contents: **${common.length} common rules**, **${packCount} language/framework packs**.`)
lines.push("")

lines.push("## Common rules (`rules/common/`)")
lines.push("")
lines.push("Apply to every project. Read before writing or reviewing code.")
lines.push("")
for (const file of common) {
  const full = path.join(commonDir, file)
  lines.push(`### ${title(full)}`)
  lines.push("")
  lines.push(`Path: \`rules/common/${file}\``)
  lines.push("")
  const summary = firstParagraph(full)
  if (summary) lines.push(summary)
  lines.push("")
}

lines.push("## Language and framework packs")
lines.push("")
lines.push("Read the pack matching the code you are touching.")
lines.push("")
for (const pack of packs) {
  if (pack === "common") continue
  const dir = path.join(rulesDir, pack)
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".md")).sort()
  if (files.length === 0) continue
  lines.push(`- **${pack}** — ${files.map((f) => `\`rules/${pack}/${f}\``).join(", ")}`)
}
lines.push("")

const outPath = path.join(opencodeDir, "RULES.md")
fs.writeFileSync(outPath, lines.join("\n"))
console.log(JSON.stringify({
  out: path.relative(process.cwd(), outPath),
  commonRules: common.length,
  packs: packs.filter((p) => p !== "common").length,
}, null, 2))
