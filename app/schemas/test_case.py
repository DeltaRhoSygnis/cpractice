"""Test-case and comparison-contract schemas.

Tests are **declarative data**, never executable code generated by an AI
(design decision #5). A test describes input, expected output, and the
comparison policy the evaluator must apply.
"""

from __future__ import annotations

from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, field_validator


class Visibility(str, Enum):
    """Whether a test's details may be shown to the learner."""

    PUBLIC = "public"
    HIDDEN = "hidden"


class ComparisonMode(str, Enum):
    """How observed output is compared against expected output."""

    # Strip CRLF -> LF; optionally tolerate a missing/extra final newline.
    EXACT_NORMALIZED = "exact_normalized"
    # Compare as whitespace-separated tokens (meaningful order preserved).
    WHITESPACE_TOLERANT = "whitespace_tolerant"


class TestCase(BaseModel):
    """A single declarative test for a C program.

    The evaluator runs the compiled program with ``stdin`` and checks
    ``stdout`` against ``expected_stdout`` using ``comparison``.
    """

    model_config = ConfigDict(extra="forbid")

    id: str = Field(min_length=1, max_length=64, pattern=r"^[a-z0-9][a-z0-9._-]*$")
    name: str = Field(min_length=1, max_length=200)
    visibility: Visibility = Visibility.PUBLIC

    stdin: str = ""
    expected_stdout: str = ""
    expected_exit_code: int = 0

    # Per-test overrides; None means "use the problem/global default".
    timeout_ms: int | None = Field(default=None, gt=0, le=60_000)
    comparison: ComparisonMode | None = None

    # Pedagogical provenance. Optional so problems authored before these
    # fields existed still load unchanged.
    #: Which stated requirement(s) this test checks, e.g. ["REQ-BOUNDARY-02"].
    requirement_ids: list[str] = Field(default_factory=list, max_length=6)
    #: Which likely misconception(s) this test exposes, e.g. ["MIS-OFF-BY-ONE-01"].
    misconception_ids: list[str] = Field(default_factory=list, max_length=6)
    #: Short note on why this case exists (author-only).
    rationale: str = Field(default="", max_length=300)

    @field_validator("id")
    @classmethod
    def _validate_id(cls, value: str) -> str:
        if value != value.lower():
            raise ValueError("test id must be lowercase")
        return value

    @property
    def is_tagged(self) -> bool:
        """True when the test declares what it is for."""
        return bool(self.requirement_ids or self.misconception_ids)

    @property
    def is_boundary(self) -> bool:
        """True when the test claims to cover a boundary or requirement."""
        return any("bound" in rid.lower() for rid in self.requirement_ids)
